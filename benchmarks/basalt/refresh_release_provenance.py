"""Synchronize the active Basalt v1 release/provenance metadata.

The v2 manifest is a frozen build/correctness binding and is generated by
``generate_provenance_manifest_v2.py``.  This helper maintains the active v1
source inventory that ``verify_provenance.py`` validates: production source
hashes, diagnostic/generator coverage, retained audit sources, the current
Cargo.lock binding in the v2 license overlay, and release artifact hashes.

Use ``--check`` in CI.  ``--write`` is explicit and deterministic.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[2]
PROVENANCE = Path("benchmarks/basalt/basalt_provenance_manifest_v1.json")
RELEASE = Path("benchmarks/basalt/basalt_release_manifest_v1.json")
LICENSE_V2 = Path("benchmarks/basalt/cargo_license_inventory_v2.json")
BENCHMARK_GENERATOR_SUFFIXES = {".cpp", ".cc", ".py", ".ps1", ".sh"}
EXAMPLE_GENERATOR_SUFFIXES = {".cpp", ".cc", ".rs", ".py", ".ps1", ".sh"}
GENERATOR_EXCLUSIONS = {
    "benchmarks/basalt/test_provenance.py",
    "benchmarks/basalt/verify_provenance.py",
    "benchmarks/basalt/refresh_provenance_hashes.py",
}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def load(root: Path, relative: Path) -> dict[str, Any]:
    value = json.loads((root / relative).read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"expected JSON object: {relative.as_posix()}")
    return value


def encode(value: dict[str, Any]) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False) + "\n"


def relative_files(root: Path, directory: Path, suffixes: set[str] | None = None) -> list[str]:
    base = root / directory
    return sorted(
        path.relative_to(root).as_posix()
        for path in base.rglob("*")
        if path.is_file() and (suffixes is None or path.suffix in suffixes)
    )


def generator_kind(relative: str) -> str:
    name = Path(relative).name
    if name.startswith("test_"):
        return "contract_test"
    if name.startswith("build_"):
        return "build_helper"
    if name.startswith("generate_"):
        return "manifest_generator"
    if name.startswith("verify_"):
        return "provenance_checker"
    if "runner" in name:
        return "performance_adapter"
    if "compare" in name:
        return "parity_checker"
    if name.endswith((".cpp", ".cc", ".rs")):
        return "diagnostic_probe"
    return "diagnostic_tool"


def sync_provenance(root: Path, payload: dict[str, Any]) -> None:
    generators = payload["checked_in_generator_hashes"]
    actual = set(
        relative_files(root, Path("benchmarks/basalt"), BENCHMARK_GENERATOR_SUFFIXES)
    )
    actual.update(
        relative_files(root, Path("pipelines/basalt/examples"), EXAMPLE_GENERATOR_SUFFIXES)
    )
    actual.difference_update(GENERATOR_EXCLUSIONS)
    for stale in set(generators).difference(actual):
        del generators[stale]
    for relative in sorted(actual):
        record = generators.setdefault(
            relative,
            {
                "kind": generator_kind(relative),
                "copied_upstream_source": False,
                "upstream_refs": ["basalt"],
            },
        )
        record["sha256"] = sha256(root / relative)

    for relative, record in payload["port_files"].items():
        if "sha256" in record:
            record["sha256"] = sha256(root / relative)
    for relative, record in payload["retained_audit_sources"].items():
        record["sha256"] = sha256(root / relative)


def sync_license(root: Path, payload: dict[str, Any]) -> None:
    payload["basis"]["lockfile_sha256"] = sha256(root / "Cargo.lock")


def sync_release(
    root: Path,
    payload: dict[str, Any],
    content_overrides: dict[str, bytes] | None = None,
) -> None:
    content_overrides = content_overrides or {}
    pipeline_tests = relative_files(root, Path("pipelines/basalt/tests"))
    contract_tests = [*pipeline_tests, "benchmarks/basalt/test_clonefree_perf.py"]
    artifacts = [item for item in payload["artifacts"] if item["kind"] != "contract_test"]
    artifacts.extend({"path": path, "kind": "contract_test"} for path in contract_tests)
    seen: set[str] = set()
    for artifact in artifacts:
        relative = artifact["path"]
        if relative in seen:
            raise ValueError(f"duplicate release artifact: {relative}")
        seen.add(relative)
        path = root / relative
        if relative in content_overrides:
            content = content_overrides[relative]
            artifact["bytes"] = len(content)
            artifact["sha256"] = sha256_bytes(content)
        elif not path.is_file():
            raise ValueError(f"missing release artifact: {relative}")
        else:
            artifact["bytes"] = path.stat().st_size
            artifact["sha256"] = sha256(path)
    payload["artifacts"] = artifacts


def synchronized(root: Path) -> dict[Path, str]:
    provenance = load(root, PROVENANCE)
    license_v2 = load(root, LICENSE_V2)
    release = load(root, RELEASE)
    sync_provenance(root, provenance)
    sync_license(root, license_v2)
    # The release manifest binds the just-refreshed provenance bytes.
    values = {PROVENANCE: encode(provenance), LICENSE_V2: encode(license_v2)}
    sync_release(
        root,
        release,
        {PROVENANCE.as_posix(): values[PROVENANCE].encode("utf-8")},
    )
    values[RELEASE] = encode(release)
    return values


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args()
    root = args.root.resolve()
    values = synchronized(root)
    changed = [relative for relative, text in values.items() if (root / relative).read_text(encoding="utf-8") != text]
    if args.check:
        for relative in changed:
            print(f"STALE {relative.as_posix()}")
        return 1 if changed else 0
    for relative, text in values.items():
        (root / relative).write_text(text, encoding="utf-8", newline="\n")
    for relative in changed:
        print(f"UPDATED {relative.as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
